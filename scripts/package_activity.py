"""Rebuild embedded artwork and package a copied presentation. Standard library only."""
import argparse
import base64
import json
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('activity', type=Path)
parser.add_argument('output', type=Path)
args = parser.parse_args()
activity = args.activity.resolve()
output = args.output.resolve()
repo = Path(__file__).resolve().parents[1]
if not (activity / 'index.html').is_file():
    parser.error('The activity directory must contain index.html.')
if output.is_relative_to(activity):
    parser.error('Write the ZIP outside the activity directory.')

sources = {}
for name, filename in [('hardware', 'hardware-atlas.png'), ('lab', 'computer-lab.png')]:
    sources[name] = 'data:image/png;base64,' + base64.b64encode((activity / 'art' / filename).read_bytes()).decode('ascii')
(activity / 'art-sources.js').write_text(
    '// Generated by scripts/package_activity.py; edit the source artwork instead.\n'
    + 'const ART_SOURCES=' + json.dumps(sources, separators=(',', ':')) + ';\n', encoding='utf-8')

output.parent.mkdir(parents=True, exist_ok=True)
prefix = Path(activity.name)
with ZipFile(output, 'w', ZIP_DEFLATED) as archive:
    for path in sorted(activity.rglob('*')):
        relative = path.relative_to(activity)
        if path.is_file() and not {'tests', '__pycache__'}.intersection(relative.parts):
            archive.write(path, prefix / relative)
    for name in ['lospec500.gpl', 'computer-club.gpl']:
        archive.write(repo / 'assets' / 'design-references' / name, prefix / 'palettes' / name)
    archive.writestr(str(prefix / 'OPEN-ME.txt'),
        'Extract this folder, then open index.html in your browser.\n'
        'Keep all files and folders together. No installation or Internet connection is needed.\n'
        'Use the Music button to toggle the original chiptune.\n'
        'Progress resets when the page reloads.\n')
with ZipFile(output) as archive:
    if archive.testzip() is not None:
        raise RuntimeError('ZIP integrity check failed.')
print(output)
